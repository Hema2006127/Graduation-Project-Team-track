// Generates supabase/seed.sql from src/services/demo/seedData.ts
// (Node >= 22.6 strips the TypeScript types natively.)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const seed = await import('../src/services/demo/seedData.ts');
const {
  SEED_SPECIALIZATIONS, SEED_MEMBERS, SEED_SESSIONS, SEED_ATTENDANCE, SEED_SETTINGS,
} = seed;

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const lines = [];
const out = (s = '') => lines.push(s);

out('-- =============================================================================');
out('-- Sample data. GENERATED by `npm run seed:sql` — do not edit by hand.');
out('-- Run after the migrations (Supabase SQL editor or `supabase db reset`).');
out('-- Session dates are relative to today in the team timezone (not the server UTC date).');
out('-- No login accounts are created: add your admin/doctor users in Supabase');
out('-- (Authentication -> Add user) and set their role in the profiles table.');
out('-- =============================================================================');
out();
out('begin;');
out();
out(`update public.app_settings set organization_name = ${q(SEED_SETTINGS.organization_name)}, timezone = ${q(SEED_SETTINGS.timezone)}, low_attendance_threshold = ${SEED_SETTINGS.low_attendance_threshold} where id = 1;`);
out();
out('insert into public.specializations (id, name, description) values');
out(SEED_SPECIALIZATIONS.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.description)})`).join(',\n') + ';');
out();
out('-- All members start active so they are added to every session roster.');
out('insert into public.team_members (id, member_code, full_name, email, phone, specialization_id, status) values');
out(SEED_MEMBERS.map((m) => `  (${q(m.id)}, ${q(m.member_code)}, ${q(m.full_name)}, ${q(m.email)}, ${q(m.phone)}, ${q(m.specialization_id)}, 'active')`).join(',\n') + ';');
out();
out('-- Sessions (the sessions_roster trigger creates an attendance row per active member).');
out('insert into public.sessions (id, title, description, session_date, start_time, end_time, doctor_id, team_group, location, notes, status, created_by) values');
out(SEED_SESSIONS.map((s) =>
  `  (${q(s.id)}, ${q(s.title)}, ${q(s.description)}, (now() at time zone ${q(SEED_SETTINGS.timezone)})::date + ${s.dayOffset}, ${q(s.start_time)}, ${q(s.end_time)}, null, ${q(s.team_group)}, ${q(s.location)}, ${q(s.notes)}, 'scheduled', null)`,
).join(',\n') + ';');
out();
out('-- Recorded attendance for past sessions.');
out('update public.attendance a set status = v.status::public.attendance_status, notes = v.notes');
out('from (values');
out(SEED_ATTENDANCE.map((r) => `  (${q(r.session_id)}::uuid, ${q(r.team_member_id)}::uuid, ${q(r.status)}, ${q(r.notes)})`).join(',\n'));
out(') as v(session_id, team_member_id, status, notes)');
out('where a.session_id = v.session_id and a.team_member_id = v.team_member_id;');
out();
const cancelled = SEED_SESSIONS.filter((s) => s.cancelled).map((s) => q(s.id));
out('-- Cancel a past session (its attendance rows stay unrecorded and never count).');
out(`update public.sessions set status = 'cancelled' where id in (${cancelled.join(', ')});`);
out();
const inactive = SEED_MEMBERS.filter((m) => m.finalStatus === 'inactive');
for (const m of inactive) {
  out(`-- ${m.full_name} left the team: keep their history, drop sessions after they left.`);
  out(`delete from public.attendance where team_member_id = ${q(m.id)} and status is null;`);
  out(`update public.team_members set status = 'inactive' where id = ${q(m.id)};`);
}
out();
out('commit;');

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(target, lines.join('\n') + '\n');
console.log(`Wrote ${target} (${SEED_SESSIONS.length} sessions, ${SEED_ATTENDANCE.length} attendance marks)`);
